CREATE OR REPLACE VIEW MIG_META.VW_MIG_RUN_SUM AS
SELECT
    DAG_NM,
    DAG_RUN_ID,
    MPG_ID,
    META_VER_NO,
    MAX(WRK_STT_DTM) AS LAST_WRK_STT_DTM,
    MAX(WRK_END_DTM) AS LAST_WRK_END_DTM,
    MAX(CASE WHEN WRK_STS_CD = 'FAILED' THEN 1 ELSE 0 END) AS FAILED_YN,
    MAX(CASE WHEN WRK_STS_CD = 'SUCCESS' THEN 1 ELSE 0 END) AS SUCCESS_YN,
    MAX(SRC_ROW_CNT) AS SRC_ROW_CNT,
    MAX(TGT_ROW_CNT) AS TGT_ROW_CNT,
    MAX(SRC_SIZE_BYTE) AS SRC_SIZE_BYTE,
    MAX(TGT_SIZE_BYTE) AS TGT_SIZE_BYTE
FROM MIG_META.TB_MIG_RUN_LOG
GROUP BY DAG_NM, DAG_RUN_ID, MPG_ID, META_VER_NO;

