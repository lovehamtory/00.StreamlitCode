WITH ALPHABET AS (
    SELECT 'A' AS ALPH_CD UNION ALL SELECT 'B' UNION ALL SELECT 'C' UNION ALL SELECT 'D' UNION ALL SELECT 'E' UNION ALL SELECT 'F' UNION ALL SELECT 'G' UNION ALL SELECT 'H' UNION ALL SELECT 'I' UNION ALL SELECT 'J' UNION ALL SELECT 'K' UNION ALL SELECT 'L' UNION ALL SELECT 'M' UNION ALL SELECT 'N' UNION ALL SELECT 'O' UNION ALL SELECT 'P' UNION ALL SELECT 'Q' UNION ALL SELECT 'R' UNION ALL SELECT 'S' UNION ALL SELECT 'T' UNION ALL SELECT 'U' UNION ALL SELECT 'V' UNION ALL SELECT 'W' UNION ALL SELECT 'X' UNION ALL SELECT 'Y' UNION ALL SELECT 'Z'
), AREA_NO AS (
    SELECT 1 AS AREA_NO UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9 UNION ALL SELECT 10
), SBJ_AREA AS (
    SELECT ALPH_CD || '01' AS SBJ_AREA_CD, NULL::VARCHAR(200) AS SBJ_AREA_NM, NULL::VARCHAR(8) AS UP_SBJ_AREA_CD, ASCII(ALPH_CD) - 64 AS DISP_ORD FROM ALPHABET
    UNION ALL
    SELECT ALPH_CD || '01' || LPAD(AREA_NO::VARCHAR, 4, '0'), NULL::VARCHAR(200), ALPH_CD || '01', (ASCII(ALPH_CD) - 64) * 100 + AREA_NO FROM ALPHABET CROSS JOIN AREA_NO
)
