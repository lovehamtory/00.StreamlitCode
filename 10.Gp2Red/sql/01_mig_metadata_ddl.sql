    T.SRC_SCH_NM,
    T.SRC_TBL_NM,
    T.TGT_CONN_ID,
    T.TGT_SCH_NM,
    T.TGT_TBL_NM,
    T.LOAD_MTHD_CD,
    T.WM_COL_NM,
    T.INCR_WHERE_TMPL,
