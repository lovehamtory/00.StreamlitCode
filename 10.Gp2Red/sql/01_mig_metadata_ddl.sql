AREA_NO AS (
    SELECT 1 AS AREA_NO UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9 UNION ALL SELECT 10
),
SBJ_AREA AS (
    SELECT ALPH_CD || '01' AS SBJ_AREA_CD, NULL::VARCHAR(200) AS SBJ_AREA_NM, NULL::VARCHAR(8) AS UP_SBJ_AREA_CD, ASCII(ALPH_CD) - 64 AS DISP_ORD
      FROM ALPHABET
    UNION ALL
    SELECT ALPH_CD || '01' || LPAD(AREA_NO::VARCHAR, 4, '0'), NULL::VARCHAR(200), ALPH_CD || '01', (ASCII(ALPH_CD) - 64) * 100 + AREA_NO
      FROM ALPHABET CROSS JOIN AREA_NO
