CREATE OR REPLACE PROCEDURE MIG_META.SP_MIG_COL_MPG_COLNO()
AS $$
DECLARE
    SRC_COL_CNT INTEGER;
    TGT_COL_CNT INTEGER;
BEGIN
    SELECT COUNT(*) INTO SRC_COL_CNT
      FROM INFORMATION_SCHEMA.COLUMNS
     WHERE TABLE_SCHEMA = 'mig_meta'
       AND TABLE_NAME = 'tb_mig_col_mpg'
       AND COLUMN_NAME = 'src_col_no';
    IF SRC_COL_CNT = 0 THEN
        EXECUTE 'ALTER TABLE MIG_META.TB_MIG_COL_MPG ADD COLUMN SRC_COL_NO INTEGER';
    END IF;
    SELECT COUNT(*) INTO TGT_COL_CNT
      FROM INFORMATION_SCHEMA.COLUMNS
     WHERE TABLE_SCHEMA = 'mig_meta'
       AND TABLE_NAME = 'tb_mig_col_mpg'
       AND COLUMN_NAME = 'tgt_col_no';
    IF TGT_COL_CNT = 0 THEN
        EXECUTE 'ALTER TABLE MIG_META.TB_MIG_COL_MPG ADD COLUMN TGT_COL_NO INTEGER';
    END IF;
END;
$$ LANGUAGE plpgsql;

CALL MIG_META.SP_MIG_COL_MPG_COLNO();
