CREATE OR REPLACE VIEW MIG_META.VW_MIG_DAG_TBL_MPG AS
SELECT T.MPG_ID, T.PRJ_CD, T.SBJ_AREA_CD, T.SRC_CONN_ID, T.SRC_SCH_NM, T.SRC_TBL_NM, T.TGT_CONN_ID, T.TGT_SCH_NM, T.TGT_TBL_NM,
       T.LOAD_STS_CD, T.INCR_BASIS_CD, T.INCR_BASIS_COL_NM, T.PARL_MTHD_CD, T.PARL_CND_ARR, T.TGT_DDL_SQL, T.META_VER_NO,
       'parquet/' || LOWER(T.PRJ_CD) || '/' || LOWER(T.SBJ_AREA_CD) || '/' || LOWER(T.SRC_SCH_NM) || '/' || LOWER(T.SRC_TBL_NM) AS S3_RLT_PATH,
       TGT.S3_STG_PATH, SRC.DBMS_CD AS SRC_DBMS_CD, TGT.DBMS_CD AS TGT_DBMS_CD,
       T.SRC_CONN_ID AS SRC_AF_CONN_ID, T.TGT_CONN_ID AS TGT_AF_CONN_ID, 'aws_default' AS S3_AF_CONN_ID
  FROM MIG_META.TB_MIG_TBL_MPG T
  JOIN MIG_META.TB_MIG_SBJ_AREA S ON S.SBJ_AREA_CD = T.SBJ_AREA_CD AND S.ACTIVE_YN = TRUE
  JOIN MIG_META.TB_MIG_CONN SRC ON SRC.CONN_ID = T.SRC_CONN_ID AND SRC.ACTIVE_YN = TRUE
  JOIN MIG_META.TB_MIG_CONN TGT ON TGT.CONN_ID = T.TGT_CONN_ID AND TGT.ACTIVE_YN = TRUE
 WHERE T.ACTIVE_YN = TRUE;

CREATE OR REPLACE VIEW MIG_META.VW_MIG_RUN_SUM AS
SELECT EXEC_RUN_ID, DAG_NM, DAG_RUN_ID, MPG_ID, MAX(META_VER_NO) AS META_VER_NO, MAX(S3_MANF_PATH) AS S3_MANF_PATH, MIN(WRK_STT_DTM) AS WRK_STT_DTM, MAX(WRK_END_DTM) AS WRK_END_DTM, DATEDIFF(second, MIN(WRK_STT_DTM), MAX(COALESCE(WRK_END_DTM, WRK_STT_DTM))) AS WRK_ELPS_SEC, MAX(CASE WHEN WRK_STS_CD = 'FAILED' THEN 1 ELSE 0 END) AS FAIL_YN, MAX(CASE WHEN WRK_STS_CD = 'RUNNING' THEN 1 ELSE 0 END) AS RUN_YN, MAX(SRC_ROW_CNT) AS SRC_ROW_CNT, MAX(TGT_ROW_CNT) AS TGT_ROW_CNT FROM MIG_META.TB_MIG_RUN_LOG GROUP BY EXEC_RUN_ID, DAG_NM, DAG_RUN_ID, MPG_ID;

CREATE OR REPLACE VIEW MIG_META.VW_MIG_DAG_RUN_SUM AS
SELECT EXEC_RUN_ID, DAG_NM, DAG_RUN_ID, COUNT(DISTINCT MPG_ID) AS TBL_CNT, SUM(CASE WHEN WRK_STS_CD = 'SUCCESS' THEN 1 ELSE 0 END) AS SUC_CNT, SUM(CASE WHEN WRK_STS_CD = 'FAILED' THEN 1 ELSE 0 END) AS FAIL_CNT, MIN(WRK_STT_DTM) AS WRK_STT_DTM, MAX(WRK_END_DTM) AS WRK_END_DTM, DATEDIFF(second, MIN(WRK_STT_DTM), MAX(COALESCE(WRK_END_DTM, WRK_STT_DTM))) AS WRK_ELPS_SEC, CASE WHEN SUM(CASE WHEN WRK_STS_CD = 'FAILED' THEN 1 ELSE 0 END) > 0 THEN 'FAILED' WHEN SUM(CASE WHEN WRK_STS_CD = 'RUNNING' THEN 1 ELSE 0 END) > 0 THEN 'RUNNING' ELSE 'SUCCESS' END AS WRK_STS_CD FROM MIG_META.TB_MIG_RUN_LOG GROUP BY EXEC_RUN_ID, DAG_NM, DAG_RUN_ID;
